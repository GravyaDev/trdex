class MarketEpisodeService:
    """High-level API for writing and querying market episodes.

    Handles embedding + storage roundtrip. Callers don't need to know about
    vectors or Qdrant directly.

    Usage::

        service = MarketEpisodeService()
        await service.setup()
        await service.record_batch(episodes)
        hits = await service.search("BTC high volatility breakout", symbol="BTC/USDT")
    """

    def __init__(
        self,
        embedder: JinaEmbedder | None = None,
        store: MarketEpisodeStore | None = None,
    ) -> None:
        self._embedder = embedder or JinaEmbedder()
        self._store = store or MarketEpisodeStore()

    async def setup(self) -> None:
        await self._store.ensure_collection()

    async def record_batch(self, episodes: list[MarketEpisode]) -> int:
        """Embed and store a batch of episodes. Returns count stored."""
        if not episodes:
            return 0
        # Ensure text is populated
        for ep in episodes:
            if not ep.text:
                ep.text = build_episode_text(ep)

        async with self._embedder as embedder:
            vectors = await embedder.embed([ep.text for ep in episodes])
        await self._store.upsert(episodes, vectors)
        logger.info("[market_episodes] recorded %d episodes", len(episodes))
        return len(episodes)

    async def search(
        self,
        query: str,
        *,
        symbol: str | None = None,
        episode_type: str | None = None,
        limit: int = 5,
    ) -> list[MarketEpisodeHit]:
        """Find episodes semantically similar to ``query``."""
        async with self._embedder as embedder:
            qvec = await embedder.embed_query(query)
        hits = await self._store.search(
            qvec, symbol=symbol, episode_type=episode_type, limit=limit
        )
        return [self._hit_from_point(h) for h in hits]

    async def search_similar_context(
        self,
        symbol: str,
        closes: list[float],
        volumes: list[float],
        *,
        limit: int = 3,
    ) -> list[MarketEpisodeHit]:
        """Find episodes similar to the current market state.

        Builds a description of the current conditions from recent closes/volumes,
        then does a semantic search to find historical episodes that looked similar.
        """
        # Build a query description from current indicators
        regime, cv = classify_volatility(closes)
        sma_s = sma_from_list(closes, 5)
        sma_l = sma_from_list(closes, 13)
        rsi_val = rsi_from_list(closes, 14)
        vol_r = volume_ratio(volumes)
        pct = (closes[-1] - closes[-20]) / closes[-20] * 100 if len(closes) >= 20 and closes[-20] != 0 else 0.0

        parts = [f"{symbol} current conditions:"]
        parts.append(f"{regime} volatility")
        if cv:
            parts.append(f"(CV={cv*100:.1f}%)")
        parts.append(f"price change {pct:+.1f}% over 20 candles")
        if rsi_val:
            parts.append(f"RSI={rsi_val:.0f}")
        if vol_r:
            parts.append(f"volume {vol_r:.1f}x baseline")
        if sma_s and sma_l:
            cross = "bullish" if sma_s > sma_l else "bearish"
            parts.append(f"SMA cross {cross}")

        query = " ".join(parts)
        return await self.search(query, symbol=symbol, limit=limit)

    async def close(self) -> None:
        await self._store.close()

    @staticmethod
    def _hit_from_point(point: ScoredPoint) -> MarketEpisodeHit:
        payload = point.payload or {}
        return MarketEpisodeHit(
            doc_id=str(point.id),
            score=float(point.score),
            text=payload.get("text", ""),
            symbol=payload.get("symbol", ""),
            timeframe=payload.get("timeframe", ""),
            episode_type=payload.get("episode_type", ""),
            price_change_pct=payload.get("price_change_pct", 0.0),
            volatility_regime=payload.get("volatility_regime", "unknown"),
            payload=payload,
        )
