"""Tier 4b — Semantic memory of historical market episodes (Qdrant).

A *market episode* captures a meaningful regime or event detected from OHLCV
data — trend reversals, volatility spikes, volume surges, consolidation
breakouts. Each episode is embedded and stored in Qdrant so the Analyst can
retrieve historically similar situations before making a decision.

Example narrative:
    "BTC/USDT 2025-11-15 to 2025-11-22 1h — High volatility regime (CV=4.2%).
     Sharp uptrend: +12.3% over 168 candles. RSI peaked at 78.
     Volume surge 2.4x baseline in first 24h. SMA5 crossed above SMA13 at start."

Design notes:
- Each episode covers a *window* of candles (not a single point). The window
  size depends on the detection algorithm (typically 20-100 candles).
- Doc ID is deterministic: ``{symbol}:{timeframe}:{window_end_ts_epoch}`` so
  re-running the generator is idempotent (upsert, not duplicate).
- The collection is separate from trade_narratives and trdex_context.
- Detection runs offline (via generate_episodes.py script), not in the hot
  path of agent cycles.
"""

from __future__ import annotations

import hashlib
import logging
from dataclasses import dataclass, field
from datetime import datetime, timezone

from qdrant_client import AsyncQdrantClient
from qdrant_client.models import (
    Distance,
    FieldCondition,
    Filter,
    HnswConfigDiff,
    MatchValue,
    PointStruct,
    ScoredPoint,
    VectorParams,
)

from trdex.backtest.indicators import (
    classify_volatility,
    rsi_from_list,
    sma_from_list,
    volume_ratio,
)
from trdex.config import get_settings
from trdex.context.embeddings import EMBEDDING_DIM, JinaEmbedder

logger = logging.getLogger(__name__)

COLLECTION_NAME = "trdex_market_episodes"


# ---------------------------------------------------------------------------
# Data classes
# ---------------------------------------------------------------------------


@dataclass
class MarketEpisode:
    """One detected market episode, ready for embedding + storage."""

    symbol: str
    timeframe: str
    episode_type: str  # trend_reversal | volatility_spike | volume_surge | consolidation_breakout | regime_change
    start_time: datetime
    end_time: datetime
    text: str = ""  # narrative — generated by build_episode_text if empty

    # Metrics at episode time
    price_change_pct: float = 0.0
    volatility_regime: str = "unknown"  # low | medium | high
    volatility_cv: float | None = None
    rsi_start: float | None = None
    rsi_end: float | None = None
    volume_ratio_peak: float | None = None
    sma_short: float | None = None
    sma_long: float | None = None
    candle_count: int = 0

    # Deterministic doc_id for idempotency
    doc_id: str = field(default="")

    def __post_init__(self) -> None:
        if not self.doc_id:
            self.doc_id = self._compute_doc_id()

    def _compute_doc_id(self) -> str:
        """Deterministic ID: hash of symbol:timeframe:end_timestamp."""
        end_epoch = int(self.end_time.timestamp())
        raw = f"{self.symbol}:{self.timeframe}:{end_epoch}"
        return hashlib.sha256(raw.encode()).hexdigest()[:32]


@dataclass
class MarketEpisodeHit:
    """A semantic search result from the episode collection."""

    doc_id: str
    score: float
    text: str
    symbol: str
    timeframe: str
    episode_type: str
    price_change_pct: float
    volatility_regime: str
    payload: dict


# ---------------------------------------------------------------------------
# Episode detection from OHLCV data
# ---------------------------------------------------------------------------


def detect_episodes(
    symbol: str,
    timeframe: str,
    timestamps: list[datetime],
    closes: list[float],
    volumes: list[float],
    window: int = 50,
    stride: int = 25,
) -> list[MarketEpisode]:
    """Detect market episodes from OHLCV close/volume data using a sliding window.

    Scans the data with a sliding window and classifies each window into
    episode types based on indicator thresholds. Only windows with a
    significant event are emitted.

    Args:
        symbol: Trading pair.
        timeframe: Candle timeframe string.
        timestamps: Ordered list of candle open times.
        closes: Ordered close prices (same length as timestamps).
        volumes: Ordered volumes (same length as timestamps).
        window: Number of candles per episode window.
        stride: Step between windows (controls overlap).

    Returns:
        List of detected MarketEpisode objects.
    """
    n = len(closes)
    if n < window:
        return []

    episodes: list[MarketEpisode] = []

    for start_idx in range(0, n - window + 1, stride):
        end_idx = start_idx + window
        w_closes = closes[start_idx:end_idx]
        w_volumes = volumes[start_idx:end_idx]
        w_start = timestamps[start_idx]
        w_end = timestamps[end_idx - 1]

        # Compute indicators for this window
        regime, cv = classify_volatility(w_closes, window=min(20, window))
        pct_change = (w_closes[-1] - w_closes[0]) / w_closes[0] * 100 if w_closes[0] != 0 else 0.0
        rsi_start = rsi_from_list(w_closes[:20], period=14) if len(w_closes) >= 20 else None
        rsi_end = rsi_from_list(w_closes, period=14)
        vol_ratio = volume_ratio(w_volumes, window=min(20, window))
        sma_s = sma_from_list(w_closes, 5)
        sma_l = sma_from_list(w_closes, 13)

        # Classify episode type based on signals
        episode_type = _classify_window(
            pct_change=pct_change,
            regime=regime,
            cv=cv,
            vol_ratio=vol_ratio,
            rsi_end=rsi_end,
            sma_short=sma_s,
            sma_long=sma_l,
        )

        if episode_type is None:
            continue  # Not significant enough

        episode = MarketEpisode(
            symbol=symbol,
            timeframe=timeframe,
            episode_type=episode_type,
            start_time=w_start,
            end_time=w_end,
            price_change_pct=round(pct_change, 3),
            volatility_regime=regime,
            volatility_cv=round(cv, 5) if cv else None,
            rsi_start=round(rsi_start, 1) if rsi_start else None,
            rsi_end=round(rsi_end, 1) if rsi_end else None,
            volume_ratio_peak=round(vol_ratio, 2) if vol_ratio else None,
            sma_short=round(sma_s, 2) if sma_s else None,
            sma_long=round(sma_l, 2) if sma_l else None,
            candle_count=window,
        )
        episode.text = build_episode_text(episode)
        episodes.append(episode)

    return episodes


def _classify_window(
    *,
    pct_change: float,
    regime: str,
    cv: float | None,
    vol_ratio: float | None,
    rsi_end: float | None,
    sma_short: float | None,
    sma_long: float | None,
) -> str | None:
    """Classify a window into an episode type, or None if unremarkable.

    Priority order (first match wins):
    1. Volume surge: vol_ratio > 2.0x
    2. Volatility spike: high regime with CV > 4%
    3. Trend reversal: abs(pct_change) > 5% with RSI extreme
    4. Consolidation breakout: low regime followed by pct_change > 3%
    5. Regime change: medium/high transition (CV boundary)

    Returns None if the window doesn't meet any threshold.
    """
    # 1. Volume surge
    if vol_ratio is not None and vol_ratio > 2.0:
        return "volume_surge"

    # 2. Volatility spike
    if regime == "high" and cv is not None and cv > 0.04:
        return "volatility_spike"

    # 3. Trend reversal (strong directional move + RSI extreme)
    if abs(pct_change) > 5.0:
        if rsi_end is not None and (rsi_end > 70 or rsi_end < 30):
            return "trend_reversal"

    # 4. Consolidation breakout (was low vol, now moved)
    if regime == "low" and abs(pct_change) > 3.0:
        return "consolidation_breakout"

    # 5. Regime change (high vol with moderate move)
    if regime == "high" and abs(pct_change) > 2.0:
        return "regime_change"

    return None


def build_episode_text(episode: MarketEpisode) -> str:
    """Render a deterministic, embedding-friendly narrative from a MarketEpisode."""
    start_str = episode.start_time.strftime("%Y-%m-%d %H:%M")
    end_str = episode.end_time.strftime("%Y-%m-%d %H:%M")

    parts: list[str] = [
        f"{episode.symbol} {start_str} to {end_str} {episode.timeframe}",
        f"— {episode.episode_type.replace('_', ' ').title()}.",
    ]

    # Volatility
    if episode.volatility_cv is not None:
        parts.append(f"{episode.volatility_regime.title()} volatility (CV={episode.volatility_cv*100:.1f}%).")

    # Price move
    direction = "uptrend" if episode.price_change_pct > 0 else "downtrend"
    parts.append(f"{'Sharp ' if abs(episode.price_change_pct) > 5 else ''}{direction}: {episode.price_change_pct:+.1f}% over {episode.candle_count} candles.")

    # RSI
    if episode.rsi_end is not None:
        rsi_label = ""
        if episode.rsi_end > 70:
            rsi_label = " (overbought)"
        elif episode.rsi_end < 30:
            rsi_label = " (oversold)"
        parts.append(f"RSI at end: {episode.rsi_end:.0f}{rsi_label}.")

    # Volume
    if episode.volume_ratio_peak is not None:
        parts.append(f"Volume {episode.volume_ratio_peak:.1f}x baseline.")

    # SMA cross
    if episode.sma_short is not None and episode.sma_long is not None:
        if episode.sma_short > episode.sma_long:
            parts.append("SMA5 above SMA13 (bullish).")
        else:
            parts.append("SMA5 below SMA13 (bearish).")

    return " ".join(parts)


