class MarketEpisodeStore:
    """Async Qdrant wrapper for the ``trdex_market_episodes`` collection."""

    def __init__(self, client: AsyncQdrantClient | None = None) -> None:
        self._client = client

    async def _get_client(self) -> AsyncQdrantClient:
        if self._client is None:
            settings = get_settings()
            self._client = AsyncQdrantClient(
                url=settings.qdrant_url, check_compatibility=False
            )
        return self._client

    async def ensure_collection(self) -> None:
        """Create the collection on first use (idempotent)."""
        client = await self._get_client()
        existing = [c.name for c in (await client.get_collections()).collections]
        if COLLECTION_NAME not in existing:
            await client.create_collection(
                collection_name=COLLECTION_NAME,
                vectors_config=VectorParams(
                    size=EMBEDDING_DIM,
                    distance=Distance.COSINE,
                    hnsw_config=HnswConfigDiff(m=16, ef_construct=100),
                ),
            )
            logger.info("[market_episodes] created collection %s", COLLECTION_NAME)

    async def upsert(
        self,
        episodes: list[MarketEpisode],
        vectors: list[list[float]],
    ) -> None:
        """Insert/update a batch of episodes with their precomputed vectors."""
        if not episodes:
            return
        if len(episodes) != len(vectors):
            raise ValueError("episodes and vectors must have the same length")

        client = await self._get_client()
        points = [
            PointStruct(
                id=ep.doc_id,
                vector=v,
                payload={
                    "text": ep.text,
                    "symbol": ep.symbol,
                    "timeframe": ep.timeframe,
                    "episode_type": ep.episode_type,
                    "start_time": ep.start_time.isoformat(),
                    "end_time": ep.end_time.isoformat(),
                    "price_change_pct": ep.price_change_pct,
                    "volatility_regime": ep.volatility_regime,
                    "volatility_cv": ep.volatility_cv,
                    "rsi_start": ep.rsi_start,
                    "rsi_end": ep.rsi_end,
                    "volume_ratio_peak": ep.volume_ratio_peak,
                    "sma_short": ep.sma_short,
                    "sma_long": ep.sma_long,
                    "candle_count": ep.candle_count,
                },
            )
            for ep, v in zip(episodes, vectors, strict=True)
        ]
        await client.upsert(collection_name=COLLECTION_NAME, points=points)

    async def search(
        self,
        query_vector: list[float],
        *,
        symbol: str | None = None,
        episode_type: str | None = None,
        limit: int = 5,
    ) -> list[ScoredPoint]:
        """Top-k semantic search with optional filters."""
        client = await self._get_client()
        must: list[FieldCondition] = []
        if symbol:
            must.append(FieldCondition(key="symbol", match=MatchValue(value=symbol)))
        if episode_type:
            must.append(FieldCondition(key="episode_type", match=MatchValue(value=episode_type)))
        query_filter = Filter(must=must) if must else None
        response = await client.query_points(
            collection_name=COLLECTION_NAME,
            query=query_vector,
            query_filter=query_filter,
            limit=limit,
            with_payload=True,
        )
        return response.points

    async def count(self, symbol: str | None = None) -> int:
        """Count episodes in the collection, optionally filtered by symbol."""
        client = await self._get_client()
        info = await client.get_collection(COLLECTION_NAME)
        if symbol is None:
            return info.points_count or 0
        # Filtered count via scroll with limit=0 is not supported;
        # use a large limit count approach
        response = await client.count(
            collection_name=COLLECTION_NAME,
            count_filter=Filter(must=[
                FieldCondition(key="symbol", match=MatchValue(value=symbol))
            ]) if symbol else None,
            exact=True,
        )
        return response.count

    async def close(self) -> None:
        if self._client:
            await self._client.close()
            self._client = None


